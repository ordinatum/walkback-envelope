/* ─────────────────────────────────────────────────────────────────────────
   WALKBACK ENVELOPE — физическое ядро
   Четыре канала расходуемых ресурсов. Все величины в СИ, без «процентов».

   Источники констант:
     Apollo EVA metabolic rates .......... 780–1200 BTU/ч (замеры на Луне)
     MSL RAD, кратер Гейла ............... 0.64 ± 0.12 мЗв/сут = 0.0267 мЗв/ч
     Теплота испарения воды (мембранный
       испаритель, 0 °C…+10 °C) .......... 2450 кДж/кг
     Калорический эквивалент O2 .......... 20.9 кДж/л STPD
   ───────────────────────────────────────────────────────────────────────── */

export const PHYS = {
  BTU_W: 0.293071,
  MARS_G: 3.721,            // м/с²
  EARTH_G: 9.807,
  MARS_R: 3396000,          // м
  // На Марсе давление (≈6–10 мбар) выше тройной точки воды (6.1 мбар), поэтому
  // сублиматор неприменим; марсианские скафандры используют мембранный
  // испаритель — вода испаряется, скрытая теплота ≈ 2.45 МДж/кг.
  H2O_EVAP: 2450e3,         // Дж/кг — теплота испарения
  O2_KJ_PER_L: 20.9,        // кДж на литр O2 (STPD)
  O2_G_PER_L: 1.429,
  RQ: 0.85,                 // респираторный коэффициент
  CO2_PER_O2_MASS: 44 / 32, // молярные массы
  DOSE_MSV_H: 0.0267,       // MSL RAD, открытая поверхность
  SUIT_BASE_W: 100,         // вентилятор, насос, связь, авионика
};

/* ── Метаболизм ───────────────────────────────────────────────────────────
   Уравнение Пандольфа, адаптированное под 0.38 g.
   Гравитационно-зависимые члены (подъём веса, работа против уклона)
   масштабируются по g. Инерционный член (разгон/торможение массы
   скафандра) от g НЕ зависит — это ключевая поправка: наивное
   умножение всей формулы на 0.38 даёт заниженный расход.        */
export function metabolicW({ bodyKg = 80, suitKg = 60, loadKg = 0,
                             speedMs = 0.39, gradePct = 0, terrain = 1.1,
                             g = PHYS.MARS_G } = {}) {
  const W = bodyKg, L = suitKg + loadKg;
  const gRatio = g / PHYS.EARTH_G;

  // базовый метаболизм покоя — от g не зависит
  const resting = 1.0 * W;
  // несение груза: гравитационная составляющая
  const carry = 2.0 * (W + L) * Math.pow(L / W, 2) * gRatio;
  // горизонтальное движение: инерция (не зависит от g) + трение о грунт
  const inertial = terrain * (W + L) * 1.5 * speedMs * speedMs;
  // работа против уклона: чисто гравитационная
  const climb = terrain * (W + L) * 0.35 * speedMs * gradePct * gRatio;

  // спуск частично возвращает энергию, но круче −20% снова дорожает (торможение)
  let total = resting + carry + inertial + climb;
  if (gradePct < 0) {
    const brake = Math.max(0, (-gradePct - 12)) * 0.9 * (W + L) * speedMs * gRatio * 0.01;
    total = resting + carry + inertial + climb * 0.35 + brake;
  }
  // скафандр добавляет накладные расходы на преодоление собственной жёсткости
  return Math.max(resting, total) * 1.18;
}

/* ── Расход по четырём каналам ───────────────────────────────────────── */
export function consumptionRates(metW, { extTempC = -60, solarWm2 = 420,
                                         evaporatorEff = 0.82 } = {}) {
  // O2: из метаболической мощности через калорический эквивалент
  const kJ_h = metW * 3.6;
  const o2_l_h = kJ_h / PHYS.O2_KJ_PER_L;
  const o2_g_h = o2_l_h * PHYS.O2_G_PER_L;

  // CO2: через респираторный коэффициент
  const co2_g_h = o2_g_h * PHYS.RQ * PHYS.CO2_PER_O2_MASS;

  // Тепловая нагрузка на мембранный испаритель.
  // Скафандр многослойно изолирован (MLI), поэтому пассивный сброс тепла
  // в космос мал — порядка 60-110 Вт, а не сотни, как даёт расчёт по
  // Стефану-Больцману для неизолированной оболочки. Весь остальной тепловой
  // поток отводится испарением воды. В нагрузку входят ВСЕ источники тепла:
  // метаболизм целиком (внешней механической работы на уровне скафандра нет —
  // она рассеивается в грунт и в тело, множитель 0.85 не обоснован) и 100 Вт
  // электроники скафандра, которые списываются с батареи и превращаются в тепло.
  // Ориентир: Apollo PLSS расходовал ~0.5 кг/ч воды при средней нагрузке выхода.
  const solarGain = solarWm2 * 0.85 * 0.30;          // площадь×поглощение
  const passiveLoss = 60 + Math.max(0, (-extTempC - 20)) * 0.75;
  const heatW = Math.max(80, metW + PHYS.SUIT_BASE_W + solarGain - passiveLoss);
  const water_kg_h = (heatW * 3600) / (PHYS.H2O_EVAP * evaporatorEff);

  // Батарея: базовая нагрузка + насос прокачки теплоносителя
  const batt_wh_h = PHYS.SUIT_BASE_W + heatW * 0.045;

  return { o2_g_h, co2_g_h, water_kg_h, batt_wh_h, heatW, metW };
}

/* ── Какой канал ограничивает ───────────────────────────────────────────
   Главный вывод предварительного расчёта: кислорода заведомо в избытке
   для 6-часового выхода. Реальные ограничители — охлаждающая вода,
   ресурс скруббера и батарея. Функция возвращает виновника по имени. */
export const CHANNELS = [
  { key: 'water', label: 'Cooling water', unit: 'kg', rate: 'water_kg_h' },
  { key: 'co2',   label: 'CO₂ scrubber',   unit: 'g',  rate: 'co2_g_h' },
  { key: 'batt',  label: 'Battery',        unit: 'Wh', rate: 'batt_wh_h' },
  { key: 'o2',    label: 'Oxygen',         unit: 'g',  rate: 'o2_g_h' },
];

export function endurance(remaining, rates) {
  let worst = { hours: Infinity, key: null, label: null };
  const per = {};
  for (const ch of CHANNELS) {
    const r = rates[ch.rate];
    const h = r > 0 ? remaining[ch.key] / r : Infinity;
    per[ch.key] = h;
    if (h < worst.hours) worst = { hours: h, key: ch.key, label: ch.label };
  }
  return { perChannel: per, limiting: worst };
}

/* ── Доза ─────────────────────────────────────────────────────────────────
   Геометрический фактор затенения: у стены кратера или в каньоне видимая
   часть неба меньше, значит поток GCR ниже. skyFraction = 1 на открытой
   равнине, ~0.5 у высокой стенки.                                        */
export function doseRateMSvH(skyFraction = 1, speEvent = false) {
  const base = PHYS.DOSE_MSV_H * Math.max(0.35, Math.min(1, skyFraction));
  return speEvent ? base * 80 : base;   // солнечная протонная вспышка
}

